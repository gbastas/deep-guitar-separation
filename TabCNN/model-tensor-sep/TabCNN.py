    def build_perfile_counts(self, batch=1024, use_mmap=True, show_pbar=True):
        """
        Fast: load each .npz once, build all context windows, predict in batches,
        compute pooled counts per file. Returns a DataFrame with one row per file:
        [file, subset, frame_tp/fp/fn, frameF0_tp/fp/fn, frame_tdr_num/den]
        """
        rows = []

        def ids_to_files(id_list):
            # e.g. 04_Jazz3-150-C_solo_012345 -> 04_Jazz3-150-C_solo
            return sorted({ "_".join(ID.split("_")[:-1]) for ID in id_list })

        def process_files(file_keys, subset_name):
            if not file_keys:
                return
            iterator = tqdm(file_keys, desc=f"{subset_name} files", leave=False) if show_pbar else file_keys
            data_dir = os.path.join(self.data_path, self.spec_repr)

            h = self.con_win_size // 2
            for fk in iterator:
                npz_path = os.path.join(data_dir, fk + ".npz")

                # Load once
                loaded = np.load(npz_path, mmap_mode='r' if use_mmap else None)
                repr_array = loaded["repr"]          # (T,H,C?) or (T,H)
                labels     = loaded["labels"]        # (T,6,21)
                if repr_array.ndim == 2:
                    repr_array = repr_array[..., None]  # -> (T,H,1)

                T = labels.shape[0]
                # Pad time and build all windows: (T, H, win, C)
                full_x = np.pad(repr_array, [(h, h), (0, 0), (0, 0)], mode='constant')
                # Simple, safe construction (fast enough; avoids stride gotchas)
                win = self.con_win_size
                X = np.stack([full_x[t:t+win] for t in range(T)], axis=0)   # (T, win, H, C)
                X = np.swapaxes(X, 1, 2)                                    # (T, H, win, C)
                X = X.astype(np.float32)

                # Predict big batch
                y_pred = self.model.predict(X, batch_size=batch, verbose=0) # (T,6,21) softmax

                # Per-file pooled counts
                counts = _perfile_counts_from_arrays(y_pred, labels)
                rows.append(dict(file=fk, subset=subset_name, **counts))

        # Unique file lists by subset (no triple loading)
        files_solo = ids_to_files(self.partition['validation-solos'])
        files_comp = ids_to_files(self.partition['validation-comps'])
        # Edge cases: validation files not in the two above (should be none, but safe)
        files_all  = ids_to_files(self.partition['validation'])
        files_other = [f for f in files_all if f not in files_solo and f not in files_comp]

        process_files(files_solo,  'solo')
        process_files(files_comp,  'comp')
        process_files(files_other, 'all')

        return pd.DataFrame(rows)



