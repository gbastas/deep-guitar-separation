_STR_REL = np.array([40, 45, 50, 55, 59, 64])  # MIDI of open strings (E2..E4)
# We use "+class - 41" (same as Metrics.tab2pitch), giving 44 bins [0..43]

def _tab2bin_batch(tab_oh: np.ndarray) -> np.ndarray:
    """
    (T,6,21) one-hot -> (T, 6*20) binary
    Drops class 0 (not-played); classes 1..20 map to frets 0..19 per string.
    """
    idx = np.argmax(tab_oh, axis=2)          # (T,6)
    T = tab_oh.shape[0]
    out = np.zeros((T, 6*20), dtype=np.int32)
    # vectorized: build mask of played notes (idx>0)
    played = idx > 0                          # (T,6)
    # fret number 0..19 where played
    fret = (idx - 1) * played                 # (T,6)
    # write ones at (t, s*20 + fret)
    t_idx, s_idx = np.where(played)
    out[t_idx, s_idx*20 + fret[t_idx, s_idx]] = 1
    return out

def _tab2pitch_batch_metrics(tab_oh: np.ndarray) -> np.ndarray:
    """
    (T,6,21) one-hot -> (T,44) binary pitch grid, following Metrics.tab2pitch:
    if class>0: pitch_idx = class + string_pitches[string] - 41
    """
    idx = np.argmax(tab_oh, axis=2)          # (T,6)
    T = tab_oh.shape[0]
    out = np.zeros((T, 44), dtype=np.int32)
    played = idx > 0                          # (T,6)
    # compute pitch indices for played notes
    # Broadcast string pitch base to (T,6)
    base = np.broadcast_to(_STR_REL, (T, 6))
    pidx = (idx + base - 41) * played         # (T,6) with 0 where not played
    # scatter
    t_idx, s_idx = np.where(played)
    out[t_idx, pidx[t_idx, s_idx]] = 1
    return out


def _one_hot_argmax(y_soft):
    """(T,6,21) -> (T,6,21) one-hot by argmax per string."""
    idx = np.argmax(y_soft, axis=2)           # (T,6)
    oh = np.zeros_like(y_soft, dtype=np.int32)
    for t in range(y_soft.shape[0]):
        for s in range(6):
            oh[t, s, idx[t, s]] = 1
    return oh

