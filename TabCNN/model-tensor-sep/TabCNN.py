def _conf_counts_bin(pred_bin, gt_bin):
    pred_b = pred_bin.astype(bool)
    gt_b   = gt_bin.astype(bool)
    tp = int(np.sum(pred_b &  gt_b))
    fp = int(np.sum(pred_b & ~gt_b))
    fn = int(np.sum(~pred_b &  gt_b))
    tn = pred_b.size - tp - fp - fn
    return tp, fp, fn, tn



def _perfile_counts_from_arrays(y_pred_soft: np.ndarray, y_gt_onehot: np.ndarray) -> dict:
    """
    y_pred_soft: (T,6,21) softmax
    y_gt_onehot: (T,6,21) one-hot
    Returns micro counts per file for TAB and PITCH + TDR numerator/denominator.
    Semantics identical to Metrics.tab2bin/tab2pitch (class 0 = not played).
    """
    # argmax -> onehot for preds
    idx = np.argmax(y_pred_soft, axis=2)
    pred_oh = np.zeros_like(y_pred_soft, dtype=np.int32)
    for t in range(y_pred_soft.shape[0]):
        for s in range(6):
            pred_oh[t, s, idx[t, s]] = 1
    gt_oh = y_gt_onehot.astype(np.int32)

    # TAB (binary over 6*20)
    pred_tab = _tab2bin_batch(pred_oh).reshape(-1).astype(bool)
    gt_tab   = _tab2bin_batch(gt_oh).reshape(-1).astype(bool)
    tp_tab = int(np.sum(pred_tab &  gt_tab))
    fp_tab = int(np.sum(pred_tab & ~gt_tab))
    fn_tab = int(np.sum(~pred_tab &  gt_tab))

    # PITCH (binary over 44)
    pred_pitch = _tab2pitch_batch_metrics(pred_oh).reshape(-1).astype(bool)
    gt_pitch   = _tab2pitch_batch_metrics(gt_oh).reshape(-1).astype(bool)
    tp_p = int(np.sum(pred_pitch &  gt_pitch))
    fp_p = int(np.sum(pred_pitch & ~gt_pitch))
    fn_p = int(np.sum(~pred_pitch &  gt_pitch))

    # TDR = TP_tab / TP_pitch (≤ 1 by construction)
    return dict(
        frame_tp=tp_tab, frame_fp=fp_tab, frame_fn=fn_tab,
        frameF0_tp=tp_p, frameF0_fp=fp_p, frameF0_fn=fn_p,
        frame_tdr_num=float(tp_tab),
        frame_tdr_den=float(tp_p),
    )



def bootstrap_micro_files(perfile_df, n_boot=10000, seed=1337, stratified=True):
    """
    Resample FILES (rows), pool counts, compute micro P/R/F1 + TDR.
    Matches Tab-Estimator bootstrap_micro for frame metrics.
    """
    rng = np.random.default_rng(seed)
    subsets = ['all']
    if 'subset' in perfile_df.columns:
        subs_found = [s for s in ['solo','comp'] if s in perfile_df['subset'].unique()]
        subsets += subs_found

    rows = []
    def summarize(a):
        a = np.asarray(a, dtype=float)
        return float(np.mean(a)), float(np.std(a, ddof=1)), float(np.percentile(a,2.5)), float(np.percentile(a,97.5))

    for subset in subsets:
        if subset == 'all':
            df = perfile_df.copy()
            has_groups = 'subset' in df.columns and set(df['subset']) & {'solo','comp'}
            n_solo = int((df['subset']=='solo').sum()) if has_groups else 0
            n_comp = int((df['subset']=='comp').sum()) if has_groups else 0
        else:
            df = perfile_df[perfile_df['subset']==subset].copy()
            has_groups = False
            n_solo = n_comp = 0

        N = len(df)
        if N == 0:
            continue

        def resample_df():
            if stratified and subset=='all' and has_groups and (n_solo+n_comp)>0:
                s = df[df['subset']=='solo']; c = df[df['subset']=='comp']
                idx_s = rng.integers(0, len(s), size=n_solo) if n_solo>0 else np.array([], int)
                idx_c = rng.integers(0, len(c), size=n_comp) if n_comp>0 else np.array([], int)
                return pd.concat([s.iloc[idx_s], c.iloc[idx_c]], ignore_index=True)
            else:
                idx = rng.integers(0, N, size=N)
                return df.iloc[idx]

        def one_metric(tp_col, fp_col, fn_col, prefix):
            p_vals, r_vals, f_vals = [], [], []
            # iterator = tqdm.trange(n_boot, desc=f"[{subset}] {prefix}", leave=False) #if show_progress else range(n_boot)
            for _ in range(n_boot):
                samp = resample_df()
                tp = float(samp[tp_col].sum()); fp = float(samp[fp_col].sum()); fn = float(samp[fn_col].sum())
                p = tp/(tp+fp) if (tp+fp)>0 else 0.0
                r = tp/(tp+fn) if (tp+fn)>0 else 0.0
                f = (2.0*tp)/(2.0*tp+fp+fn) if (2.0*tp+fp+fn)>0 else 0.0
                p_vals.append(p); r_vals.append(r); f_vals.append(f)
            for name, arr in [('p',p_vals),('r',r_vals),('f1',f_vals)]:
                mean, std, lo, hi = summarize(arr)
                rows.append(dict(subset=subset, metric=f'{prefix}_{name}',
                                 mean=mean, std=std, ci95_lo=lo, ci95_hi=hi))

        def one_tdr(num_col, den_col, name):
            if num_col in df.columns and den_col in df.columns:
                vals = []
                for _ in range(n_boot):
                    samp = resample_df()
                    num = float(samp[num_col].sum()); den = float(samp[den_col].sum())
                    vals.append((num/den) if den>0 else 0.0)
                mean, std, lo, hi = summarize(vals)
                rows.append(dict(subset=subset, metric=name,
                                 mean=mean, std=std, ci95_lo=lo, ci95_hi=hi))

        one_metric('frameF0_tp','frameF0_fp','frameF0_fn','frameF0')
        one_metric('frame_tp',  'frame_fp',  'frame_fn',  'frame')
        one_tdr('frame_tdr_num','frame_tdr_den','frame_tdr')

    return pd.DataFrame(rows).round(3)

def print_bootstrap_summary_files(boot_df: pd.DataFrame):
    def get_mean_hw(subset, metric):
        m = boot_df[(boot_df['subset']==subset) & (boot_df['metric']==metric)]
        if m.empty: return None, None
        mean = float(m.iloc[0]['mean'])
        hw = float(m.iloc[0]['ci95_hi'] - m.iloc[0]['ci95_lo'])/2.0
        return round(mean,3), round(hw,3)

    def fmt(xy):
        m, hw = xy
        return r"{:.3f} ± {:.3f}".format(m, hw) if (m is not None and hw is not None) else r"—"

    # Order matches your Tab-Estimator printout
    print(r"PP & PR & PF & TP & TR & TF & TDR & PFSolo & TFSolo & PFComp & TFComp ")

    # overall
    f_PP = get_mean_hw('all','frameF0_p'); f_PR = get_mean_hw('all','frameF0_r'); f_PF = get_mean_hw('all','frameF0_f1')
    f_TP = get_mean_hw('all','frame_p');   f_TR = get_mean_hw('all','frame_r');   f_TF = get_mean_hw('all','frame_f1')
    f_TDR= get_mean_hw('all','frame_tdr')

    # subsets (F1 only)
    f_PFs = get_mean_hw('solo','frameF0_f1'); f_TFs = get_mean_hw('solo','frame_f1')
    f_PFc = get_mean_hw('comp','frameF0_f1'); f_TFc = get_mean_hw('comp','frame_f1')

    print("{} & {} & {} & {} & {} & {} & {} & {} & {} & {} & {} ".format(
        fmt(f_PP), fmt(f_PR), fmt(f_PF), fmt(f_TP), fmt(f_TR), fmt(f_TF), fmt(f_TDR),
        fmt(f_PFs), fmt(f_TFs), fmt(f_PFc), fmt(f_TFc)
    ))




