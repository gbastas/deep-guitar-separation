def _tab2pitch_batch(tab_onehot):
    """(N,6,21) -> (N,44) pitch bins by argmax per string; ignore 'not played' (>=20)."""
    rel = [0,5,10,15,19,24]
    idx = np.argmax(tab_onehot, axis=2)  # (N,6)
    N = tab_onehot.shape[0]
    pitch = np.zeros((N,44), dtype=np.int32)
    for i in range(N):
        for s in range(6):
            a = idx[i, s]
            if a < 20:
                pitch[i, a + rel[s]] = 1
    return pitch


