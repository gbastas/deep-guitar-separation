def mean_pm_ci(series, alpha: float = 0.05):
    """Return (mean, ±halfwidth) where halfwidth is ~95% CI (normal approx)."""
    arr = np.asarray(series, dtype=np.float64)
    n = arr.size
    if n == 0:
        return float("nan"), float("nan")
    m = float(arr.mean())
    if n == 1:
        return m, 0.0
    hw = 1.96 * float(arr.std(ddof=1)) / math.sqrt(n)  # ~95% CI half-width
    return m, hw

def confusion_counts(pred: np.ndarray, gt: np.ndarray):
    """Binary arrays -> (tp, fp, fn, tn) as ints."""
    pred_b = pred.astype(bool)
    gt_b = gt.astype(bool)
    tp = int(np.sum(pred_b & gt_b))
    fp = int(np.sum(pred_b & ~gt_b))
    fn = int(np.sum(~pred_b & gt_b))
    tn = pred_b.size - tp - fp - fn
    return tp, fp, fn, tn

def prf_from_counts(tp: int, fp: int, fn: int):
    p = tp / (tp + fp) if (tp + fp) > 0 else 0.0
    r = tp / (tp + fn) if (tp + fn) > 0 else 0.0
    f = (2 * tp) / (2 * tp + fp + fn) if (2 * tp + fp + fn) > 0 else 0.0
    return p, r, f

def bootstrap_summary(perfile: pd.DataFrame, n_boot: int = 1000, seed: int = 1337,
                      stratified: bool = True) -> pd.DataFrame:
    """
    Bootstrap over files. Returns long-format DF with mean/std/CI for:
      - macro (mean across files): frame_f1, note_f1, frame_F0_f1, note_F0_f1, frame_tdr, note_tdr
      - micro (via counts): frame_micro_f1, note_micro_f1, frameF0_micro_f1, noteF0_micro_f1 (+ p, r)
    Runs for subsets: 'all' and available ['solo','comp'].
    """
    rng = np.random.default_rng(seed)

    # which subsets exist?
    subsets = ['all']
    if 'subset' in perfile.columns:
        subs_found = [s for s in ['solo', 'comp'] if s in perfile['subset'].unique()]
        subsets += subs_found

    rows = []
    for subset in subsets:
        if subset == 'all':
            df = perfile.copy()
            # optional stratified bootstrap to preserve solo/comp balance
            has_groups = 'subset' in df.columns and set(df['subset']) & {'solo','comp'}
            n_solo = int((df['subset'] == 'solo').sum()) if has_groups else 0
            n_comp = int((df['subset'] == 'comp').sum()) if has_groups else 0
        else:
            df = perfile[perfile['subset'] == subset].copy()
            has_groups = False  # single group
        N = len(df)
        if N == 0:
            continue

        # arrays for macro metrics
        def boots_stat(get_vals):
            vals = []
            for _ in range(n_boot):
                if stratified and subset == 'all' and has_groups and (n_solo + n_comp) > 0:
                    idx_s = rng.integers(0, (df['subset'] == 'solo').sum(), size=n_solo) if n_solo > 0 else np.array([], int)
                    idx_c = rng.integers(0, (df['subset'] == 'comp').sum(), size=n_comp) if n_comp > 0 else np.array([], int)
                    df_s = df[df['subset'] == 'solo'].iloc[idx_s] if n_solo > 0 else df.iloc[0:0]
                    df_c = df[df['subset'] == 'comp'].iloc[idx_c] if n_comp > 0 else df.iloc[0:0]
                    samp = pd.concat([df_s, df_c], ignore_index=True)
                else:
                    idx = rng.integers(0, N, size=N)
                    samp = df.iloc[idx]
                vals.append(np.mean(get_vals(samp)))
            vals = np.array(vals, dtype=np.float64)
            return float(np.mean(vals)), float(np.std(vals, ddof=1)), float(np.percentile(vals, 2.5)), float(np.percentile(vals, 97.5))

        # macro: simple means over files
        macro_targets = {
            'frame_macro_f1':  lambda d: d['frame_f1'].values,
            'note_macro_f1':   lambda d: d['note_f1'].values,
            'frameF0_macro_f1':lambda d: d['frame_F0_f1'].values,
            'noteF0_macro_f1': lambda d: d['note_F0_f1'].values,
            'frame_macro_tdr': lambda d: d['frame_tdr'].values,
            'note_macro_tdr':  lambda d: d['note_tdr'].values,
        }

        for name, getter in macro_targets.items():
            mean, std, lo, hi = boots_stat(getter)
            rows.append(dict(subset=subset, metric=name, mean=mean, std=std, ci95_lo=lo, ci95_hi=hi))

        # micro: aggregate TP/FP/FN over the sampled set
        def boots_micro(tp_col, fp_col, fn_col, name_prefix):
            f_vals, p_vals, r_vals = [], [], []
            for _ in range(n_boot):
                if stratified and subset == 'all' and has_groups and (n_solo + n_comp) > 0:
                    idx_s = rng.integers(0, (df['subset'] == 'solo').sum(), size=n_solo) if n_solo > 0 else np.array([], int)
                    idx_c = rng.integers(0, (df['subset'] == 'comp').sum(), size=n_comp) if n_comp > 0 else np.array([], int)
                    samp = pd.concat([
                        df[df['subset']=='solo'].iloc[idx_s] if n_solo>0 else df.iloc[0:0],
                        df[df['subset']=='comp'].iloc[idx_c] if n_comp>0 else df.iloc[0:0]
                    ], ignore_index=True)
                else:
                    idx = rng.integers(0, N, size=N)
                    samp = df.iloc[idx]
                tp = int(samp[tp_col].sum()); fp = int(samp[fp_col].sum()); fn = int(samp[fn_col].sum())
                p, r, f = prf_from_counts(tp, fp, fn)
                p_vals.append(p); r_vals.append(r); f_vals.append(f)
            def summarize(a):
                a = np.array(a, dtype=np.float64)
                return float(np.mean(a)), float(np.std(a, ddof=1)), float(np.percentile(a, 2.5)), float(np.percentile(a, 97.5))
            for suffix, arr in [('f1', f_vals), ('p', p_vals), ('r', r_vals)]:
                mean, std, lo, hi = summarize(arr)
                rows.append(dict(subset=subset, metric=f'{name_prefix}_micro_{suffix}', mean=mean, std=std, ci95_lo=lo, ci95_hi=hi))

        boots_micro('frame_tp','frame_fp','frame_fn','frame')
        boots_micro('note_tp','note_fp','note_fn','note')
        boots_micro('frameF0_tp','frameF0_fp','frameF0_fn','frameF0')
        boots_micro('noteF0_tp','noteF0_fp','noteF0_fn','noteF0')

    return pd.DataFrame(rows)



def calculate_metrics(pred, gt):
    precision, recall, f1, _ = precision_recall_fscore_support(
        gt, pred, average='binary')

    return precision, recall, f1


def tab2pitch(tab):
    rel_string_pitches = [0, 5, 10, 15, 19, 24]
    argmax_index = np.argmax(tab, axis=2)
    pitch = np.zeros((len(tab), 44))
    for time in range(len(tab)):
        for string in range(6):
            if argmax_index[time, string] < 20:
                pitch[time, argmax_index[time, string] +
                      rel_string_pitches[string]] = 1

    return pitch


def TDR(tab_pred, tab_gt, F0_gt):
    F0_from_tab_pred = tab2pitch(tab_pred)

    TP_tab = np.multiply(tab_gt[:, :, :-1], tab_pred[:, :, :-1]).sum()
    TP_F0 = np.multiply(F0_gt, F0_from_tab_pred).sum()
    tdr = TP_tab / TP_F0
    return tdr


